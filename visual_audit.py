    ap.add_argument("--password", default=os.environ.get("SCORR_AUTH_PASSWORD", ""))
    ap.add_argument("--poll-seconds", type=int, default=int(os.environ.get("VISUAL_AUDIT_POLL_SECONDS", "60")))
    ap.add_argument("--once", action="store_true", help="one poll iteration (drain requests, crawl if due), then exit")
