def execute_actions(page, actions):
    """cc#2012 item 5: a request row's `actions` -- a JSON list of {"click": "<selector>"} and
    {"wait_ms": N} steps, run after load and before the capture, so a popup, a modal or a tab state
    can be photographed (the black-popup-on-light-theme class lives behind a tap). BOUNDED by design:
    at most MAX_ACTION_STEPS, only these two step shapes, selector strings only -- there is no path
    here that evaluates arbitrary JS, and an unrecognised step is skipped, never executed."""
    if not actions or not isinstance(actions, list):
        return 0
    ran = 0
    for step in actions[:MAX_ACTION_STEPS]:
        if not isinstance(step, dict):
            continue
        if "click" in step and isinstance(step["click"], str) and step["click"].strip():
            page.locator(step["click"]).first.click(timeout=5000)
            ran += 1
        elif "wait_ms" in step:
            page.wait_for_timeout(max(0, min(int(step["wait_ms"]), 10000)))  # cap a single wait at 10s
            ran += 1
    return ran


def capture_one(page, base_url, route_path, theme, viewport_name, width, height, actions=None):
    """One route x theme x viewport: navigate, settle, run any requested actions, then take the
    JPEG and the five checks. Returns the image BYTES (cc#2012 item 1: JPEG quality 80, ~60-120KB
    each, captured for EVERY capture pass or fail -- the founder's storage revision that limited the
    image to failures is superseded by cc#2012's own spec_source). `page.screenshot()` with no path
    returns bytes -- nothing is written to the container's disk any more, which is the whole point:
    that disk was the write-only trap cc#2012 exists to fix."""
    page.set_viewport_size({"width": width, "height": height})
    sep = "&" if "?" in route_path else "?"
    url = base_url.rstrip("/") + route_path + sep + "theme=" + theme
    result = {"route": route_path, "theme": theme, "viewport": viewport_name,
              "status": "ok", "error": None, "checks": [], "content_hash": None,
              "image_bytes": None, "image_mime": None, "actions_ran": 0}
    try:
        page.goto(url, wait_until="domcontentloaded", timeout=20000)
        try:
            page.wait_for_load_state("networkidle", timeout=8000)
        except Exception:
            pass  # a page with a long-poll/live connection never goes idle -- proceed on what rendered
        page.wait_for_timeout(500)  # settle: async paints (cc#1133's own "settle_ms" precedent)
        result["actions_ran"] = execute_actions(page, actions)
        if result["actions_ran"]:
            page.wait_for_timeout(300)  # let whatever the action opened finish painting
        html = page.content()
        result["content_hash"] = hashlib.sha256(html.encode("utf-8", "ignore")).hexdigest()[:16]
        result["image_bytes"] = page.screenshot(type="jpeg", quality=80, full_page=True)
        result["image_mime"] = "image/jpeg"
        result["checks"] = run_checks(page)
    except Exception as e:
        result["status"] = "error"
        result["error"] = f"{type(e).__name__}: {str(e)[:300]}"
    return result


def _write_capture(cur, run_id, cap):
    """Write one capture row + its check rows, then apply retention for its (route, theme,
    viewport) combo. Returns (capture_id, has_fail). Shared by the daily crawl and the on-demand
    request path so both write identically -- one writer, not two."""
    has_fail = cap["status"] == "error" or any(c["status"] == "FAIL" for c in cap["checks"])
    cur.execute(
        """INSERT INTO visual_audit_captures
           (run_id, route, theme, viewport, content_hash, image_bytes, image_mime, has_check_fail, status, error)
           VALUES (%s,%s,%s,%s,%s,%s,%s,%s,%s,%s) RETURNING id""",
        (run_id, cap["route"], cap["theme"], cap["viewport"], cap["content_hash"],
         cap["image_bytes"], cap["image_mime"], has_fail, cap["status"], cap["error"]))
    capture_id = cur.fetchone()[0]
    for c in cap["checks"]:
        cur.execute(
            """INSERT INTO visual_audit_results
               (run_id, capture_id, route, theme, viewport, check_name, status, selector, measured, expected, detail)
               VALUES (%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s)""",
            (run_id, capture_id, cap["route"], cap["theme"], cap["viewport"],
             c["check"], c["status"], c["selector"], c["measured"], c["expected"], c["detail"]))
    _apply_retention(cur, cap["route"], cap["theme"], cap["viewport"], capture_id)
    return capture_id, has_fail


def _apply_retention(cur, route, theme, viewport, keep_id):
    """cc#2012 item 1 retention, per (route, theme, viewport) combo: the row just written (keep_id)
    is the LATEST and its bytes are kept indefinitely -- it is excluded from this UPDATE entirely.
    Every OLDER row of the SAME combo keeps its bytes only if it recorded a check FAIL and is still
    within 7 days; everything else has its bytes nulled. The ROW itself is never deleted here --
    measurements, hash and status stay queryable forever, exactly cc#2007's own "PASS and FAIL
    rows both kept, only the image is conditional" principle, now applied per-combo rather than
    per-run. `has_check_fail` is a column on the captures row (set at insert) so this is one
    index-friendly statement, not a per-row join against visual_audit_results."""
    cur.execute(
        """UPDATE visual_audit_captures
           SET image_bytes = NULL, image_mime = NULL
           WHERE route = %s AND theme = %s AND viewport = %s AND id <> %s
             AND image_bytes IS NOT NULL
             AND NOT (has_check_fail AND captured_at >= now() - interval '7 days')""",
        (route, theme, viewport, keep_id))


def _viewport(name):
    for vp_name, w, h in VIEWPORTS:
        if vp_name == name:
            return vp_name, w, h
    raise ValueError(f"unknown viewport '{name}' -- one of {[v[0] for v in VIEWPORTS]}")


def _record_run(conn, status, error=None, duration_ms=None):
    """Update the scheduler_master row this worker is registered under (ENGINE_LIVENESS_RULE 13829:
    last_run_at is the liveness evidence, the badge follows the data). Never raises -- a registry
    write failing must not take the crawl down with it."""
    try:
        with conn.cursor() as cur:
            cur.execute("""UPDATE scheduler_master SET last_run_at=NOW(), last_status=%s, last_error=%s,
                           last_duration_ms=%s WHERE job_name='visual_audit_crawl'""",
                        (status, (error or None) and str(error)[:500], duration_ms))
        conn.commit()
    except Exception as e:
        log.warning("scheduler_master record_run failed: %s", e)


ROUTE_MAP_UNMAPPED = "unmapped"


def sync_route_map(conn, routes, run_id):
    """Fable's addendum on cc#2012 (cc_task_logs 6427): at the start of every full crawl, upsert
    app_route_map from the SAME parse_nav_routes output the crawl walks, so the table can never
    drift from the live nav. Only what the NAV itself carries is written: route, label, nav_flag,
    nav_position, and surface (flag 'm' = mobile, anything else = web -- the exact split the table
    holds today). What only Fable knows -- route_group, serving_file, handler, template -- is NEVER
    overwritten: an existing row keeps its mapping untouched; a route new to the nav lands with the
    literal sentinel 'unmapped' in those columns plus a WARNING, so Fable fills it in rather than
    the crawler guessing a handler. Rows whose route has left the nav are NOT deleted (the table is
    Fable's) -- they are reported as stale in the return value and the log. Never raises: a map
    failure must not stop the crawl that follows it."""
    out = {"upserted": 0, "new": [], "stale": []}
    try:
        with conn.cursor() as cur:
            cur.execute("SELECT route FROM app_route_map")
            existing = {r[0] for r in cur.fetchall()}
            nav_paths = []
            for pos, r in enumerate(routes, start=1):
                path = r["path"]
                nav_paths.append(path)
                if path not in existing:
                    out["new"].append(path)
                cur.execute(
                    """INSERT INTO app_route_map
                           (route, label, surface, nav_flag, route_group, serving_file, handler,
                            template, nav_position, source, added_by)
                       VALUES (%s, %s, %s, %s, %s, %s, %s, NULL, %s, %s, 'visual_audit')
                       ON CONFLICT (route) DO UPDATE SET
                           label = EXCLUDED.label,
                           surface = EXCLUDED.surface,
                           nav_flag = EXCLUDED.nav_flag,
                           nav_position = EXCLUDED.nav_position""",
                    (path, r["label"], "mobile" if r["flag"] == "m" else "web", r["flag"],
                     ROUTE_MAP_UNMAPPED, ROUTE_MAP_UNMAPPED, ROUTE_MAP_UNMAPPED, pos,
                     f"pwa_endpoints.py NAV array, visual_audit crawl {run_id}"))
                out["upserted"] += 1
            out["stale"] = sorted(existing - set(nav_paths))
        conn.commit()
        if out["new"]:
            log.warning("app_route_map: %d route(s) new to the nav, inserted as '%s' -- Fable to map: %s",
                        len(out["new"]), ROUTE_MAP_UNMAPPED, out["new"])
        if out["stale"]:
            log.warning("app_route_map: %d row(s) no longer in the live nav (left in place): %s",
                        len(out["stale"]), out["stale"])
    except Exception as e:
        try:
            conn.rollback()
        except Exception:
            pass
        out["error"] = f"{type(e).__name__}: {str(e)[:300]}"
        log.warning("app_route_map sync failed (crawl continues): %s", e)
    return out


def run_crawl(page, base_url, conn, routes=None, themes=None, viewports=None):
    """The FULL crawl: every NAV route x theme x viewport. Takes an already-logged-in page and an
    open connection (the worker owns both for its whole lifetime) rather than opening its own, so
    the daily crawl and the on-demand poller share one browser session and one login."""
    run_id = uuid.uuid4().hex[:16]
    routes = routes if routes is not None else parse_nav_routes()
    themes = themes or THEMES
    viewports = viewports or VIEWPORTS
    summary = {"run_id": run_id, "routes_enumerated": len(routes), "captures": 0,
               "checks_run": 0, "failures_by_check": {}, "worst_routes": {},
               "route_map": sync_route_map(conn, routes, run_id)}
    t0 = time.time()
    with conn.cursor() as cur:
        for route in routes:
            for theme in themes:
                for vp_name, w, h in viewports:
                    cap = capture_one(page, base_url, route["path"], theme, vp_name, w, h)
                    summary["captures"] += 1
                    _write_capture(cur, run_id, cap)
                    for c in cap["checks"]:
                        summary["checks_run"] += 1
                        if c["status"] == "FAIL":
                            summary["failures_by_check"][c["check"]] = summary["failures_by_check"].get(c["check"], 0) + 1
                            summary["worst_routes"][cap["route"]] = summary["worst_routes"].get(cap["route"], 0) + 1
                    conn.commit()
    summary["worst_routes"] = dict(sorted(summary["worst_routes"].items(), key=lambda kv: -kv[1])[:10])
    summary["duration_ms"] = int((time.time() - t0) * 1000)
    _record_run(conn, "ok", duration_ms=summary["duration_ms"])
    return summary


def process_requests(page, base_url, conn):
    """cc#2012 item 4(a): drain visual_audit_requests WHERE status='pending'. Each request is one
    capture (route, theme, viewport, optional actions) written through the SAME _write_capture the
    daily crawl uses, then the request row is set done+capture_id or error+message. Oldest first.
    A single bad request (unknown viewport, a selector that never appears) is recorded on ITS row
    and does not stop the rest of the queue."""
    with conn.cursor() as cur:
        cur.execute("""SELECT id, route, theme, viewport, actions FROM visual_audit_requests
                       WHERE status='pending' ORDER BY requested_at ASC LIMIT 20""")
        pending = cur.fetchall()
    done = 0
    for req_id, route, theme, viewport, actions in pending:
        try:
            with conn.cursor() as cur:
                cur.execute("UPDATE visual_audit_requests SET status='running', updated_at=now() WHERE id=%s", (req_id,))
            conn.commit()
            vp_name, w, h = _viewport(viewport)
            if theme not in THEMES:
                raise ValueError(f"unknown theme '{theme}' -- one of {THEMES}")
            if isinstance(actions, str):
                actions = json.loads(actions)
            cap = capture_one(page, base_url, route, theme, vp_name, w, h, actions=actions)
            with conn.cursor() as cur:
                capture_id, _ = _write_capture(cur, "req-" + uuid.uuid4().hex[:8], cap)
                if cap["status"] == "error":
                    cur.execute("""UPDATE visual_audit_requests SET status='error', error=%s, capture_id=%s,
                                   updated_at=now() WHERE id=%s""", (cap["error"], capture_id, req_id))
                else:
                    cur.execute("""UPDATE visual_audit_requests SET status='done', capture_id=%s, error=NULL,
                                   updated_at=now() WHERE id=%s""", (capture_id, req_id))
            conn.commit()
            done += 1
        except Exception as e:
            conn.rollback()
            try:
                with conn.cursor() as cur:
                    cur.execute("""UPDATE visual_audit_requests SET status='error', error=%s, updated_at=now()
                                   WHERE id=%s""", (f"{type(e).__name__}: {str(e)[:400]}", req_id))
                conn.commit()
            except Exception as e2:
                log.error("could not even record the error on request %s: %s", req_id, e2)
    return done


def daily_crawl_due(conn, now_ist=None):
    """cc#2012 item 4(b): the full crawl runs once a day at 03:00 IST, decided HERE with a real
    Asia/Kolkata clock -- not by Railway cron, which is UTC-only ('0 3 * * *' there is 08:30 IST,
    mid-session, the exact thing that must not happen). Due when: it is at or past 03:00 IST today
    AND scheduler_master.last_run_at (the registry's own liveness stamp) is not already from today
    in IST. A restart at 14:00 IST on a day the 03:00 run was missed therefore runs it once, then
    waits for tomorrow -- catches up, never double-runs."""
    now_ist = now_ist or datetime.now(IST)
    if now_ist.hour < 3:
        return False
    with conn.cursor() as cur:
        cur.execute("SELECT last_run_at FROM scheduler_master WHERE job_name='visual_audit_crawl'")
        row = cur.fetchone()
    last = row[0] if row else None
    if last is None:
        return True
    if last.tzinfo is None:
        last = last.replace(tzinfo=timezone.utc)
    return last.astimezone(IST).date() < now_ist.date()


def launch_browser(p):
    """cc#2014 item 2 -- boot-time preflight, BEFORE login. Launch the browser Playwright resolves
    itself (or CC_CHROMIUM if explicitly set), log the resolved browser version so the Deploy Logs
    prove the process got past the launch, and hand the browser back. If launch fails, log the
    reason and the path it tried at ERROR and exit non-zero -- the 12-Sep crash was visible only in
    Railway's Deploy Logs, with nothing in the app naming the cause. Raises SystemExit(1) on failure
    so Railway's ON_FAILURE restart policy takes over."""
    kwargs = {"headless": True}
    if CHROME:
        kwargs["executable_path"] = CHROME
    where = f"CC_CHROMIUM={CHROME}" if CHROME else "Playwright's bundled browser (no executable_path)"
    try:
        browser = p.chromium.launch(**kwargs)
    except Exception as e:
        log.error("browser launch FAILED using %s: %s: %s", where, type(e).__name__, str(e).strip()[:600])
        raise SystemExit(1)
    log.info("browser ready: chromium %s via %s", browser.version, where)
    return browser


def worker(base_url, password, poll_seconds=60, once=False):
    """The long-running process (cc#2012 item 4). One browser, one login, one DB connection, held
    for the life of the process. Every `poll_seconds`: drain pending on-demand requests, then run the
    daily crawl if it is due. Non-fatal errors (one request failing, a transient DB hiccup) are
    logged and the loop continues; a fatal error (login impossible, browser gone) propagates and the
    process exits so Railway's restart policy takes over. `once=True` runs a single iteration -- the
    manual-trigger / smoke-test path."""
    from playwright.sync_api import sync_playwright

    with sync_playwright() as p:
        browser = launch_browser(p)       # cc#2014 preflight: logs the version, or exits non-zero
        context = browser.new_context()
        page = context.new_page()
        login(page, base_url, password)   # raises -> fatal -> exit, per cc#2007's own gate
        conn = _conn()
        try:
            while True:
                try:
                    n = process_requests(page, base_url, conn)
                    if n:
                        log.info("processed %d on-demand capture request(s)", n)
                    if daily_crawl_due(conn):
                        log.info("daily crawl due (IST) -- starting")
                        s = run_crawl(page, base_url, conn)
                        log.info("daily crawl done: %s", json.dumps(s))
                except psycopg.OperationalError as e:
                    log.warning("DB hiccup, reconnecting: %s", e)
                    try:
                        conn.close()
                    except Exception:
                        pass
                    conn = _conn()
                except Exception as e:
                    log.error("worker iteration failed (continuing): %s", e, exc_info=True)
                    try:
                        conn.rollback()
                    except Exception:
                        pass
                if once:
                    break
                time.sleep(poll_seconds)
        finally:
            conn.close()
            browser.close()


